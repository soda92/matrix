package main

import (
	"unicode"
	"unicode/utf8"
)

// langDef is a named glyph set. wide means each glyph is drawn in a
// two-column cell, as CJK terminals do.
type langDef struct {
	name  string
	chars []rune
	wide  bool
}

// langOrder is the order used when cycling languages at runtime.
var langOrder = []string{"classic", "latin", "jp", "cn", "tw", "kr"}

var langs = buildLangs()

func buildLangs() map[string]*langDef {
	m := make(map[string]*langDef)
	add := func(name string, wide bool, text string, aliases ...string) {
		def := &langDef{name: name, chars: splitRunes(text), wide: wide}
		m[name] = def
		for _, alias := range aliases {
			m[alias] = def
		}
	}
	add("classic", false, classicChars, "default", "kana")
	add("latin", false, latinChars, "en", "ascii")
	add("jp", true, jpChars, "ja", "japanese")
	add("cn", true, cnChars, "zh", "zh-cn", "zh-hans", "chinese", "simplified")
	add("tw", true, twChars, "zh-tw", "zh-hant", "traditional")
	add("kr", true, krChars, "ko", "korean", "hangul")
	return m
}

func lookupLang(name string) (*langDef, bool) {
	def, ok := langs[name]
	return def, ok
}

// splitRunes turns a block of text into a de-duplicated rune set, dropping
// whitespace so the sets can be wrapped across source lines.
func splitRunes(s string) []rune {
	seen := make(map[rune]bool, 1024)
	out := make([]rune, 0, 1024)
	for _, r := range s {
		if unicode.IsSpace(r) || r == utf8.RuneError || !unicode.IsPrint(r) || seen[r] {
			continue
		}
		seen[r] = true
		out = append(out, r)
	}
	return out
}

func anyWide(chars []rune) bool {
	for _, r := range chars {
		if isWideRune(r) {
			return true
		}
	}
	return false
}

// isWideRune reports whether r occupies two terminal cells. It covers the
// ranges used by the built-in sets; ambiguous-width characters are treated as
// narrow, which matches most terminals.
func isWideRune(r rune) bool {
	switch {
	case r >= 0x1100 && r <= 0x115F, // Hangul Jamo
		r >= 0x2E80 && r <= 0xA4CF,   // CJK radicals, kana, Han, Yi
		r >= 0xAC00 && r <= 0xD7A3,   // Hangul syllables
		r >= 0xF900 && r <= 0xFAFF,   // CJK compatibility ideographs
		r >= 0xFE30 && r <= 0xFE6F,   // CJK compatibility forms
		r >= 0xFF01 && r <= 0xFF60,   // fullwidth forms
		r >= 0xFFE0 && r <= 0xFFE6,   // fullwidth signs
		r >= 0x20000 && r <= 0x3FFFD: // CJK extension planes
		return true
	}
	return false
}

